val signingProperties = Properties().apply {
    val candidates = listOf(
        rootProject.file("keystore.properties"),
        File(System.getProperty("user.home"), ".config/sukashi-map/keystore.properties"),
    )
    candidates.firstOrNull { it.exists() }?.inputStream()?.use { load(it) }
}

fun signingValue(environmentName: String, propertyName: String): String? =
    System.getenv(environmentName)?.takeIf { it.isNotBlank() }
        ?: signingProperties.getProperty(propertyName)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("SUKASHI_KEYSTORE_PATH", "storeFile")
val releaseStorePassword = signingValue("SUKASHI_KEYSTORE_PASSWORD", "storePassword")
val releaseKeyAlias = signingValue("SUKASHI_KEY_ALIAS", "keyAlias")
val releaseKeyPassword = signingValue("SUKASHI_KEY_PASSWORD", "keyPassword")
val hasReleaseSigning =
    releaseStoreFile != null &&
        releaseStorePassword != null &&
        releaseKeyAlias != null &&
        releaseKeyPassword != null &&
        file(releaseStoreFile).exists()

