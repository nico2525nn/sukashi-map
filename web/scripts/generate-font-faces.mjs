#!/usr/bin/env node
/**
 * Generate woff2-only, unicode-range split @font-face CSS for the bundled
 * Japanese fonts.
 *
 * Fontsource ships each Japanese weight as one large file and as 120
 * unicode-range subsets. Using the subsets lets a browser download only the
 * glyph ranges that the current page and watermark actually render instead of
 * the whole 1.2-2.2 MB font. The woff fallback is dropped because every
 * browser that can run this app supports woff2.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const families = ['kaisei-tokumin', 'noto-sans-jp', 'noto-serif-jp']
const outDir = join(root, 'src', 'generated')
mkdirSync(outDir, { recursive: true })

for (const family of families) {
  const source = readFileSync(
    join(root, 'node_modules', '@fontsource', family, '700.css'),
    'utf8',
  )
  const blocks = [...source.matchAll(/@font-face\s*\{[^}]*\}/g)].map((match) => {
    const block = match[0].replace(
      /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\),\s*url\(\.\/files\/[^)]+\.woff\)\s*format\('woff'\)/,
      `url('@fontsource/${family}/files/$1') format('woff2')`,
    )
    return block
  })
  if (blocks.length === 0 || blocks.some((block) => block.includes("format('woff')"))) {
    throw new Error(`Unexpected @font-face format in ${family}/700.css`)
  }
  const output = `/* Generated by scripts/generate-font-faces.mjs. Do not edit. */\n${blocks.join('\n')}\n`
  writeFileSync(join(outDir, `font-faces-${family}.css`), output)
  console.log(`${family}: ${blocks.length} unicode-range faces`)
}
